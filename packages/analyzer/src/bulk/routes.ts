interface SetClassEntry {
  forte: string;
  primeForm: number[];
  intervalVector: [number, number, number, number, number, number];
  cardinality: number;
  abstractGroup: string;
  mullikenLabel: string;
  stabilizerOrder: number;
  maximallyEven: boolean;
  myhillProperty: boolean;
}

let _setClassCache: SetClassEntry[] | null = null;

function buildSetClasses(): SetClassEntry[] {
  if (_setClassCache) return _setClassCache;

  _setClassCache = FORTE_CATALOG.map(([forte, pcs]) => {
    const typedPcs = pcs as PitchClass[];
    const analysis = classify(typedPcs);
    return {
      forte,
      primeForm: typedPcs,
      intervalVector: analysis.intervalVector,
      cardinality: pcs.length,
      abstractGroup: analysis.abstractGroup,
      mullikenLabel: analysis.mullikenLabel,
      stabilizerOrder: analysis.stabilizerOrder,
      maximallyEven: analysis.maximallyEven,
      myhillProperty: analysis.myhillProperty,
    };
  });

  return _setClassCache;
}

// ---------------------------------------------------------------------------
// GET /api/bulk/set-classes — all 224 set classes
// ---------------------------------------------------------------------------
bulkRouter.get(
  '/set-classes',
  requireTier('research'),
  rateLimit('bulk'),
  (_req, res) => {
    const entries = buildSetClasses();
    res.json({ count: entries.length, setClasses: entries });
  },
);

// ---------------------------------------------------------------------------
// GET /api/bulk/set-classes/:forte — single set class by Forte number
// ---------------------------------------------------------------------------
bulkRouter.get(
  '/set-classes/:forte',
  requireTier('research'),
  rateLimit('bulk'),
  (req, res) => {
    const forte = req.params.forte;
    const entry = buildSetClasses().find(e => e.forte === forte);
    if (!entry) {
      res.status(404).json({ error: `Set class '${forte}' not found` });
      return;
    }
    res.json(entry);
  },
);

// ---------------------------------------------------------------------------
// POST /api/bulk/classify — batch classify up to 5000 sets
// ---------------------------------------------------------------------------
bulkRouter.post(
  '/classify',
  requireTier('research'),
  rateLimit('bulk'),
  (req, res) => {
    try {
      const { sets } = req.body as { sets?: unknown };
      if (!Array.isArray(sets)) {
        res.status(400).json({ error: 'Body must contain a "sets" array' });
        return;
      }
      if (sets.length > 5000) {
        res.status(400).json({ error: 'Maximum 5000 sets per bulk request' });
        return;
      }

      const results = (sets as unknown[]).map((pcsRaw, index) => {
        if (!Array.isArray(pcsRaw) || pcsRaw.length < 2) {
          return { index, error: 'Need at least 2 pitch classes' };
        }
        const pcs = (pcsRaw as number[]).map(Number).filter(n => n >= 0 && n <= 11) as PitchClass[];
        if (pcs.length < 2) {
          return { index, error: 'Need at least 2 valid pitch classes (0–11)' };
        }
        const analysis = classify(pcs);
        const chord = pcs.length === 3 ? identifyChord(pcs) : null;
        return { index, analysis, chord };
      });

      res.json({ results, count: results.length });
    } catch (err) {
      res.status(500).json({ error: err instanceof Error ? err.message : 'Unknown error' });
    }
  },
);
